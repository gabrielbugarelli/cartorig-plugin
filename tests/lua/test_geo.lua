local geo = require("CartoRig.geo")
local function almost(a,b)
  assert(math.abs(a-b) < 1e-7, string.format("%.10f differs from %.10f",a,b))
end
assert(geo.normalize_longitude(190)==-170)
assert(geo.normalize_longitude(-180)==-180)
assert(geo.normalize_longitude(540)==-180)
assert(geo.normalize_longitude(-540)==-180)
assert(geo.unwrap_near(-179,179)==181)
assert(geo.unwrap_near(179,-179)==-181)
assert(geo.validate_latitude(90)==90)
assert(geo.validate_latitude(-90)==-90)
assert(geo.validate_latitude(91)==nil)
assert(geo.validate_latitude(0/0)==nil)
assert(geo.validate_longitude(math.huge)==nil)
assert(geo.validate_anchor({latitude=25, longitude=190}).longitude==-170)
assert(geo.validate_anchor({latitude=95, longitude=0})==nil)
assert(geo.distinct_endpoints({latitude=0,longitude=180},{latitude=0,longitude=-180})==nil)
assert(geo.distinct_endpoints({latitude=0,longitude=179},{latitude=0,longitude=-179})==true)
local base={latitude=0, longitude=0, zoom=1, bearing=0}
local p=assert(geo.project(0,0,base,1920,1080))
almost(p.x,960);almost(p.y,540)
almost(geo.fit_world_scale(1920,1080),1920/360)
local ne=assert(geo.project(10,20,base,1920,1080))
almost(ne.x,960+20*1920/360)
almost(ne.y,540-10*1920/360)
local qhd=assert(geo.project(0,0,base,2560,1440))
almost(qhd.x,1280);almost(qhd.y,720)
local uhd=assert(geo.project(0,0,base,3840,2160))
almost(uhd.x,1920);almost(uhd.y,1080)
local coast=assert(geo.project(0,-179,{latitude=0,longitude=179,zoom=2,bearing=0},1920,1080))
almost(coast.x,960+2*(1920/360)*2)
local rotated=assert(geo.project(0,10,{latitude=0,longitude=0,zoom=1,bearing=90},1920,1080))
almost(rotated.x,960);assert(rotated.y>540)
assert(geo.project(0,0,{latitude=0,longitude=0,zoom=100,bearing=0},1920,1080)==nil)
assert(geo.project(0,0,base,-1,1080)==nil)
print("geo: PASS (projection, anchors, dateline, resolutions, camera validation)")
